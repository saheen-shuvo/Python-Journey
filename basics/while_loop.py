# WHILE LOOP

i = 0
while i < 5:
    print(i, "Hello World!")
    i += 1

    # Output:
    #0  Hello World!
    #1  Hello World!
    #2  Hello World!
    #3  Hello World!
    #4  Hello World!

    # While loop will continue to execute the block of code as long as the condition is true. In this case, it will print "Hello World!" and the value of i until i is no longer less than 5.