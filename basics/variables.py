# Variables:
#Variables are used to store data in memory. They can hold different types of data, such as numbers, strings, lists, and more. In Python, you can create a variable by assigning a value to it using the equals sign (=).

# Example of creating variables:
# Integer variable
age = 25
# String variable
name = "John"
# Float variable
height = 5.9
# Boolean variable
is_student = True
# List variable
fruits = ["apple", "banana", "cherry"]
# Dictionary variable
person = {"name": "Alice", "age": 30, "city": "New York"}
# You can also change the value of a variable by reassigning it:
age = 26  # Now age is 26 instead of 25

# You can use variables in expressions and functions. For example:
# Using variables in an expression
total_age = age + 5  # total_age will be 31
print(total_age)

#Variables Naming Rules:
# 1. Variable names must start with a letter or an underscore (_).
# 2. Variable names can contain letters, numbers, and underscores.
# 3. Variable names are case-sensitive (e.g., age and Age are different variables).
# 4. Variable names should not be Python reserved keywords (e.g., if, else, while, etc.).
# 5. Variable names should be descriptive and meaningful to improve code readability.